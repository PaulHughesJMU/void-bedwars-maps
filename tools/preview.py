SEE_THROUGH = (0, 20, 102, 166)

PALETTE = np.zeros((256, 16, 3), np.uint8)
PALETTE[:, :] = (128, 128, 128)
for i, c in BLOCK.items():
    PALETTE[i, :] = c
for i, cs in BY_DATA.items():
    m = DATA_MASK.get(i, 15)
    for d in range(16):
        PALETTE[i, d] = cs[d & m] if (d & m) < len(cs) else cs[0]


def render(path, vol, data, exclude=None, target=640):
    """exclude: (x0,y0,z0,x1,y1,z1) inclusive box in volume coords left out of the render."""
    from PIL import Image
    ids = vol
    if exclude is not None:
        x0, y0, z0, x1, y1, z1 = exclude
        ids = vol.copy()
        ids[max(y0, 0):y1 + 1, max(z0, 0):z1 + 1, max(x0, 0):x1 + 1] = 0
    solid = ~np.isin(ids, SEE_THROUGH)
    footprint = solid.any(axis=0)
    if footprint.any():
        # a sealed roof (some duels maps) would hide everything: cut a near-full layer with air under it
        cov = solid.reshape(solid.shape[0], -1)[:, footprint.ravel()].mean(axis=1)
        full = np.flatnonzero(cov >= 0.9)
        if len(full):
            top, y = full[-1], full[-1]
            while y > 0 and cov[y - 1] >= 0.9:
                y -= 1
            gap = 16
            if (top - y < 3 and y > gap and (cov[top + 1:] < 0.05).all() and (cov[y - gap:y] < 0.25).all()
                    and cov[:y - gap].sum() > 0.5):
                solid[y:] = False
    H = ids.shape[0]
    top = H - 1 - np.argmax(solid[::-1], axis=0)
    has = solid.any(axis=0)
    zz, xx = np.indices(top.shape)
    tid = ids[top, zz, xx]
    tdat = data[top, zz, xx] & 15
    rgb = PALETTE[tid, tdat].astype(np.float32)
    h = np.where(has, top, 0).astype(np.float32)
    north = np.vstack([h[:1], h[:-1]])
    shade = np.clip(1.0 + (h - north) * 0.06, 0.72, 1.18)
    if has.any():
        lo, hi = h[has].min(), h[has].max()
        shade *= 0.88 + 0.24 * ((h - lo) / max(hi - lo, 1))
    rgb = np.clip(rgb * shade[..., None], 0, 255).astype(np.uint8)
    alpha = np.where(has, 255, 0).astype(np.uint8)
    img = Image.fromarray(np.dstack([rgb, alpha]), "RGBA")
    scale = max(1, min(8, round(target / max(img.size))))
    if scale > 1:
        img = img.resize((img.width * scale, img.height * scale), Image.NEAREST)
    img.save(path, optimize=True)
